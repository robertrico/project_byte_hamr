CNTH DS 1

MAIN JSR CROUT
* MLI PREFIX EMPTY AT BOOT: BUILD
* FROM LAST DEVICE VIA ON_LINE
 JSR MLI
 DFB $C7 ; GET_PREFIX
 DA GPPARM
 LDA PFXBUF
 BNE :pfok
 LDA $BF30
 STA OLUNIT
 JSR MLI
 DFB $C5 ; ON_LINE
 DA OLPARM
 BCS :pfok
 LDA OLBUF
 AND #$0F
 BEQ :pfok
 TAX
 LDY #0
:pcp LDA OLBUF+1,Y
 STA PFXBUF+2,Y
 INY
 DEX
 BNE :pcp
 LDA #'/'
 STA PFXBUF+1
 LDA OLBUF
 AND #$0F
 CLC
 ADC #1
 STA PFXBUF
 JSR MLI
 DFB $C6 ; SET_PREFIX
 DA GPPARM
:pfok LDX #<MSGF1
 LDY #>MSGF1
 JSR PRSTR
 JSR GETLN1
 CPX #0
 BNE :hv1
 RTS
:hv1 STX PATH1
 LDY #0
:cp1 LDA $200,Y
 JSR UPC
 STA PATH1+1,Y
 INY
 DEX
 BNE :cp1
 LDX #<MSGF2
 LDY #>MSGF2
 JSR PRSTR
 JSR GETLN1
 CPX #0
 BNE :hv2
 RTS
:hv2 STX PATH2
 LDY #0
:cp2 LDA $200,Y
 JSR UPC
 STA PATH2+1,Y
 INY
 DEX
 BNE :cp2
