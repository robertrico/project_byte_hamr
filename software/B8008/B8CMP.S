* COMPARE CNT BYTES. GLOBAL LABELS:
* SELF-MOD TARGETS END LOCAL SCOPE.
CMPLP LDA CNTL
 ORA CNTH
 BEQ CMPDN
CP1 LDA $FFFF
 STA B1V
CP2 LDA $FFFF
 CMP B1V
 BNE CDIFF
 INC CP1+1
 BNE CMA
 INC CP1+2
CMA INC CP2+1
 BNE CMB
 INC CP2+2
CMB INC OFFL
 BNE CMC
 INC OFFH
CMC LDA CNTL
 BNE CMD
 DEC CNTH
CMD DEC CNTL
 JMP CMPLP

* EQUAL SO FAR: EOF/LENGTH CHECKS
CMPDN LDA R1TRANS
 CMP R2TRANS
 BNE LENDIF
 LDA R1TRANS+1
 CMP R2TRANS+1
 BNE LENDIF
 CMP #2 ; FULL 512 = MORE
 BNE PASS
 JMP CHUNK

