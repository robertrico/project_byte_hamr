* CHUNK LOOP: READ 512 FROM EACH
CHUNK LDA #0
 STA R1TRANS
 STA R1TRANS+1
 STA R2TRANS
 STA R2TRANS+1
 JSR MLI
 DFB $CA ; READ 1
 DA R1PARM
 BCC :r1
 CMP #$4C ; EOF IS FINE
 BEQ :r1
 JMP MERR
:r1 JSR MLI
 DFB $CA ; READ 2
 DA R2PARM
 BCC :r2
 CMP #$4C
 BEQ :r2
 JMP MERR
:r2
* CNT = MIN(T1,T2)
 LDA R1TRANS+1
 CMP R2TRANS+1
 BCC :t1
 BNE :t2
 LDA R1TRANS
 CMP R2TRANS
 BCC :t1
:t2 LDA R2TRANS
 STA CNTL
 LDA R2TRANS+1
 STA CNTH
 JMP :go
:t1 LDA R1TRANS
 STA CNTL
 LDA R1TRANS+1
