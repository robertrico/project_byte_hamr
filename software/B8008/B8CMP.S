* B8CMP.S - COMPARE TWO PRODOS FILES
* BRUN B8CMP. PROMPTS FOR TWO FILES,
* STREAMS BOTH VIA MLI (512B CHUNKS),
* PRINTS PASS+SIZE OR FIRST DIFF.
* ASM8 GATE TOOL: PROVE OBJECT ==
* REFERENCE BYTE-FOR-BYTE ON THE E.
* NO ZERO PAGE (SELF-MOD POINTERS).
 ORG $2000
 JMP MAIN

MLI = $BF00
GETLN1 = $FD6F
COUT = $FDED
PRBYTE = $FDDA
CROUT = $FD8E
IOBUF1 = $8C00
IOBUF2 = $9000
BUF1 = $4000
BUF2 = $4200
CR = $0D

B1V DS 1
D1V DS 1
D2V DS 1
ERRB DS 1
OFFL DS 1
OFFH DS 1
