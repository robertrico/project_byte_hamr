* ASM8.S - NATIVE 8008 ASSEMBLER
* BRUN ASM8. PROMPTS FOR A TXT SOURCE
* IN TRUE 8008 SYNTAX (ASL 8008NEW),
* STREAMING TWO-PASS ASSEMBLE, WRITES
* BIN OBJECT WITH AUX TYPE = ORG.
* RUN OBJECTS WITH: B8RUN <NAME>.
* THIN FILE DRIVER AROUND ASM8CORE
* (SEAMS: SRCOPEN/SRCLINE/SRCDONE,
* OINIT/OSTORE, ERRHOOK).
* DESIGN VALIDATED BY ASM8_CHECK.PY
* (SAME SPEC, BYTE-IDENTICAL 6/6).
* NO ZERO PAGE (SELF-MOD POINTERS).
 ORG $2000
 JMP MAIN

