* ---- CORE SEAM: SOURCE ----
SRCOPEN JSR MLI
 DFB $C8 ; OPEN SRC
 DA OPARM
 BCC RDO1
 JMP MERR
RDO1 LDA OREF
 STA RREF
 STA RCREF
 LDA #0
 STA CAVL
 STA CAVH
 STA EOFF
 RTS
* NEXT RAW BYTE. C=1 AT EOF.
RDBYTE LDA CAVL
 ORA CAVH
 BNE RDB2
 LDA EOFF
 BEQ RDB3
 SEC
 RTS
RDB3 LDA #0
 STA RTRANS
 STA RTRANS+1
 JSR MLI
 DFB $CA ; READ 512
 DA RPARM
 BCC RDB4
 CMP #$4C ; EOF IS FINE
 BEQ RDB4
 JMP MERR
RDB4 LDA RTRANS
 ORA RTRANS+1
 BNE RDB5
 LDA #1
 STA EOFF
 SEC
 RTS
RDB5 LDA RTRANS
 STA CAVL
 LDA RTRANS+1
 STA CAVH
 LDA #<CHUNKB
 STA RDB1+1
 LDA #>CHUNKB
 STA RDB1+2
RDB2 LDA CAVL
 BNE RDB6
 DEC CAVH
RDB6 DEC CAVL
RDB1 LDA $FFFF
 INC RDB1+1
 BNE RDB7
 INC RDB1+2
RDB7 CLC
 RTS
* NEXT LINE -> LINEB. C=1 NO MORE.
* STRIP HI BIT, TAB->SPC, UPCASE.
SRCLINE LDA #0
 STA LINEL
RL1 JSR RDBYTE
 BCS RLEOF
 AND #$7F
 CMP #CR
 BEQ RLCR
 CMP #$0A ; LF SKIPPED
 BEQ RL1
 CMP #9
 BNE RL2
 LDA #' '
RL2 JSR UPC
 LDX LINEL
 CPX #127
 BCS RLLONG
 STA LINEB,X
 INC LINEL
 JMP RL1
RLLONG LDX #<ELONG
 LDY #>ELONG
 JMP ERRHOOK
RLCR CLC
 RTS
RLEOF LDA LINEL
 BEQ RLE2
 CLC ; LAST LINE, NO CR
 RTS
RLE2 SEC
 RTS
SRCDONE JSR MLI
 DFB $CC ; CLOSE SRC
 DA RCPARM
 LDA #0
 STA OREF
 RTS

