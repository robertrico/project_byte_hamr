* WRITE OBJECT: DESTROY STALE FILE,
* CREATE BIN AUX=ORG, WRITE, CLOSE
WROBJ JSR MLI
 DFB $C1 ; DESTROY
 DA DPARM
 BCC :cr
 CMP #$46 ; NOT FOUND = FINE
 BEQ :cr
 JMP MERR
:cr LDA ORGL
 STA CRAUX
 LDA ORGH
 STA CRAUX+1
 JSR MLI
