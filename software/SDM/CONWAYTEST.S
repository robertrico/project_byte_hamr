* CONWAYTEST.S - Conway/Life coproc self-test
* BRUN CONWAY_TEST. Seeds oracle patterns,
* rings the LIFE skill one gen (on-demand,
* deterministic), reads back + asserts.
* TEXT (LIFE8) + GR (LIFE8GR), LSIM=0 blobs.
* Mirrors FARM_TEST framework.
* Build: make conwaytest. Burn disk. BRUN.
 TYP $06
 DSK CONWAYTEST.bin
 ORG $2000
 JMP MAIN
 PUT FARMEQU
 PUT SDRAMLIB
 PUT CPLIB
* --- ZP (non-ProDOS transient) ---
SRC = $0C
MSGPTR = $0A
* --- SCRATCH (inline) ---
CNT DS 2
RSTWT DS 2
NPASS DS 1
