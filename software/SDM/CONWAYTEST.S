* === LIFETICK: ring skill 1 (LIFE1 one tick) ===
* Calls CP_CALL(skill=1,arg0=0,budget=0),
* CP_WAIT, CP_RESULT. C=1 if no slot free.
LIFETICK
 LDA #1
 LDX #0
 LDY #0
 JSR CP_CALL
 CMP #$FF
 BNE LTKWT
 LDA #<LLSPWN
 STA MSGPTR
 LDA #>LLSPWN
 STA MSGPTR+1
 JSR PRFAIL
 SEC
 RTS
LTKWT
 STA CVHND
 LDA CVHND
 JSR CP_WAIT
 LDA CVHND
 JSR CP_RESULT
 CLC
 RTS

