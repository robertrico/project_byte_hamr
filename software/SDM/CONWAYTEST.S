* === LOADLIFE: LSKILL -> coproc $0300 ===
* TABLE[0]=$0300 (LIFE8 forever)
* TABLE[1]=$0303 (LIFE1 single tick + DONE)
LOADLIFE
 LDA #$00
 STA CP_LADDRLO
 LDA #$03
 STA CP_LADDRHI
 LDA #<LSKILL
 STA SRC
 LDA #>LSKILL
 STA SRC+1
 LDA #<LSKLEN
 STA CNT
 LDA #>LSKLEN
 STA CNT+1
 LDY #0
LLLP
 LDA (SRC),Y
 STA CP_WDATA
 INC SRC
 BNE LLDC
 INC SRC+1
LLDC
 LDA CNT
 SEC
 SBC #1
 STA CNT
 LDA CNT+1
 SBC #0
 STA CNT+1
 ORA CNT
 BNE LLLP
* TABLE[0/1] at coproc $0200-$0203
