* === LRD: read bank UBASE(16) A=lo Y=hi ===
LRD
 STA SDM_ADDR
 STY SDM_ADDR+1
 LDA #UBASE
 STA SDM_BANK
 LDA #0
 STA SDM_BANK+1
 JSR SDM_READ
 RTS

* === LWR: write SDM_VAL to UBASE A=lo Y=hi ===
LWR
 STA SDM_ADDR
 STY SDM_ADDR+1
 LDA #UBASE
 STA SDM_BANK
 LDA #0
 STA SDM_BANK+1
 JSR SDM_WRITE
 RTS

* === MWR: write SDM_VAL to CMBANK A=lo Y=hi ===
MWR
 STA SDM_ADDR
 STY SDM_ADDR+1
 LDA #CMBANK
 STA SDM_BANK
 LDA #0
 STA SDM_BANK+1
 JSR SDM_WRITE
 RTS

* === LRDCHK: read UBASE A=lo Y=hi, cmp TEXP ===
LRDCHK
 JSR LRD
 LDA SDM_VAL
 CMP TEXP
 BEQ LRCKP
 JMP PRFAIL
LRCKP
 JMP PRPASS

* === RSTWAIT: poll CP_FSTAT bit 1 ===
RSTWAIT
 LDA #0
 STA RSTWT
 STA RSTWT+1
RSWLP
 LDA CP_FSTAT
 AND #2
 BNE RSWDN
 INC RSTWT
 BNE RSWLP
 INC RSTWT+1
 BNE RSWLP
RSWDN
 RTS

* === PRCHR: A=char -> COUT (set hi bit) ===
PRCHR
