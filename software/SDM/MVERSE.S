* MVERSE.S - CONWAY MULTIVERSE DHGR RENDER
* HOST //e SIDE. ORG $6000. BRUN BIN.
* READS ONE UNIVERSE GRID FROM SDRAM AND
* BLITS IT TO DOUBLE HI-RES (560x192).
* GRID ROW = 80 BYTES (ROWBYTES):
*  EVEN BYTE -> AUX  ODD BYTE -> MAIN
* BIT0 = LEFTMOST = DHGR LSB (R9):
*  STRAIGHT BYTE COPY, NO BIT REVERSAL.
* TASK 4 = RENDER HALF. TASK 5 = SURF LOOP.
 TYP $06
 DSK MVERSE.bin
 ORG $6000

 JMP MAIN
 PUT LIFEMAP
 PUT SDRAMLIB
 PUT LINEADDR

* --- DHGR SOFT SWITCHES ---
S80STON = $C001
S80VID = $C00D
HIRESON = $C057
DHIRON = $C05E
MIXOFF = $C052
GRAPH = $C050
PAGE2ON = $C055
PAGE2OF = $C054

* --- 40 BYTES PER BANK PER SCANLINE ---
NCOLS = ROWBYTES/2

* --- ZP LINE-BASE POINTER (NON-PRODOS) ---
LINEP = $06

* === RENDER STATE (INLINE STORAGE) ===
CHAN DS 1
ROW DS 1
LIVEBAS DS 2
PROD DS 2
T16 DS 2
LINEBUF DS 80

* === DHGRON: ENABLE DOUBLE HI-RES ===
DHGRON
 STA S80STON
 STA HIRESON
 STA DHIRON
 STA S80VID
 STA MIXOFF
 STA GRAPH
 RTS

* === DHGRCLR: ZERO AUX THEN MAIN BANK ===
* NEEDS 80STORE+HIRES ON (DHGRON FIRST)
DHGRCLR
 STA PAGE2ON
 JSR CLRPG
 STA PAGE2OF
 JSR CLRPG
 RTS

* CLRPG: ZERO $2000-$3FFF (CURRENT BANK)
CLRPG
 LDA #$00
 STA LINEP
 LDA #$20
 STA LINEP+1
 LDY #0
 TYA
CLRLP
 STA (LINEP),Y
 INY
 BNE CLRLP
 INC LINEP+1
 LDX LINEP+1
 CPX #$40
 BNE CLRLP
 RTS

* === RENDER: BLIT UNIVERSE CHAN TO DHGR ===
RENDER
* --- READ FRONT[CHAN] FROM MBANK $10+CHAN ---
 LDA #MBANK
 STA SDM_BANK
 LDA #0
 STA SDM_BANK+1
 LDA #$10
 CLC
 ADC CHAN
 STA SDM_ADDR
 LDA #0
 STA SDM_ADDR+1
 JSR SDM_READ
* --- LIVE BASE = FRONT? BUFB : BUFA ---
 LDA SDM_VAL
 BNE RFRONT
 LDA #<BUFA
 STA LIVEBAS
 LDA #>BUFA
 STA LIVEBAS+1
 JMP RBASEOK
RFRONT
 LDA #<BUFB
 STA LIVEBAS
 LDA #>BUFB
 STA LIVEBAS+1
RBASEOK
* --- GRID BANK = UBASE+CHAN ---
 LDA #UBASE
 CLC
 ADC CHAN
 STA SDM_BANK
 LDA #0
 STA SDM_BANK+1
 JSR SDM_SETBANK
* --- WALK ALL NROWS SCANLINES ---
 LDA #0
 STA ROW
RROW
* SDM_ADDR = LIVEBAS + ROW*80
 LDA ROW
 JSR MUL80
 CLC
 LDA LIVEBAS
 ADC PROD
 STA SDM_ADDR
 LDA LIVEBAS+1
 ADC PROD+1
 STA SDM_ADDR+1
 JSR SDM_SETADDR
* READ 80 GRID BYTES INTO LINEBUF
 LDY #0
RDLP
 JSR SDM_RDNEXT
 LDA SDM_VAL
 STA LINEBUF,Y
 INY
 CPY #ROWBYTES
 BNE RDLP
* LINE BASE PTR FROM LINEADDR HI:LO
 LDX ROW
 LDA HI,X
 STA LINEP+1
 LDA LO,X
 STA LINEP
* AUX PASS: EVEN BYTES 0,2..78
 STA PAGE2ON
 LDX #0
 LDY #0
AUXLP
 LDA LINEBUF,X
 STA (LINEP),Y
 INX
 INX
 INY
 CPY #NCOLS
 BNE AUXLP
* MAIN PASS: ODD BYTES 1,3..79
 STA PAGE2OF
 LDX #1
 LDY #0
MAINLP
 LDA LINEBUF,X
 STA (LINEP),Y
 INX
 INX
 INY
 CPY #NCOLS
 BNE MAINLP
* NEXT ROW
 INC ROW
 LDA ROW
 CMP #NROWS
 BNE RROW
 RTS

* === MUL80: PROD = A * 80 ===
MUL80
 STA PROD
 LDA #0
 STA PROD+1
 LDX #4
MULSH
 ASL PROD
 ROL PROD+1
 DEX
 BNE MULSH
 LDA PROD
 STA T16
 LDA PROD+1
 STA T16+1
 ASL PROD
 ROL PROD+1
 ASL PROD
 ROL PROD+1
 CLC
 LDA PROD
 ADC T16
 STA PROD
 LDA PROD+1
 ADC T16+1
 STA PROD+1
 RTS

* === MAIN: INIT + RENDER CHAN 0 ONCE ===
* TASK 5 REPLACES THIS WITH SURF LOOP.
MAIN
 JSR SDM_READY
 BCC MRDY
 RTS
MRDY
 JSR DHGRON
 JSR DHGRCLR
 LDA #0
 STA CHAN
 JSR RENDER
 RTS
