* EVLIB.S - COPROC EVENT RING PUBLISH
* PUT-INCLUDE. NO ORG. NEEDS FARMEQU.
* CALLER SETS EVTYPE EVP0 EVP1, JSR PUTEV.
* ORDER (NORMATIVE): RECORD, SEQCTR++, HEAD++.
* ABS SCRATCH + GBANK/FSEQC/FHEAD/FRING COME
* FROM THE INCLUDER'S EQU FILE (NO ZP)

PUTEV
* read SEQCTR and HEAD (one burst)
 SEI
 LDA #FSEQC
 STA RADDRLO
 LDA #$00
 STA RADDRHI
 LDA #GBANK
 STA RBANKR
 STA RTRIG
 LDA RDATA
 STA EVSEQ
 STA RTRIG
 LDA RDATA
 STA EVHEAD
 CLI
* record lo = HEAD*4 (ring page-aligned at
* $0100: hi const, max lo 63*4=252, no carry)
 LDA EVHEAD
 ASL
 ASL
 STA EVRLO
* write record: SEQ TYPE P0 P1 (hi = >FRING)
 SEI
 LDA #GBANK
 STA SBANKR
 LDA #>FRING
 STA SADDRHI
 LDA EVRLO
 STA SADDRLO
 LDA EVSEQ
 STA SDATA
 INC EVRLO
 LDA EVRLO
 STA SADDRLO
 LDA EVTYPE
 STA SDATA
 INC EVRLO
 LDA EVRLO
 STA SADDRLO
 LDA EVP0
 STA SDATA
 INC EVRLO
 LDA EVRLO
 STA SADDRLO
 LDA EVP1
 STA SDATA
* SEQCTR++ THEN HEAD++ (LAST) - PAGE 0 AGAIN
 LDA #$00
 STA SADDRHI
 LDA #FSEQC
 STA SADDRLO
 LDA EVSEQ
 CLC
 ADC #1
 STA SDATA
 LDA #FHEAD
 STA SADDRLO
 LDA EVHEAD
 CLC
 ADC #1
 AND #$3F
 STA SDATA
 CLI
 RTS
