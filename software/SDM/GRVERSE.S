* GRVERSE.S - CONWAY MULTIVERSE GR RENDER
* HOST //e SIDE. ORG $6000. BRUN BIN.
* READS ONE UNIVERSE GRID FROM SDRAM AND
* BLITS IT TO LO-RES (40x48 BLOCKS).
* GRID ROW = 5 BYTES (ROWBYTES), 8 CELLS
* PER BYTE, BIT0 = LEFTMOST CELL.
* TEXT-PAGE BYTE = 2 STACKED BLOCKS:
*  LOW NIBBLE = TOP, HIGH NIBBLE = BOTTOM.
* TASK 3 = RENDER HALF. TASK 4 = SURF LOOP.
 TYP $06
 DSK GRVERSE.bin
 ORG $6000

 JMP MAIN
 PUT LIFEMAPGR
 PUT SDRAMLIB

* --- LO-RES SOFT SWITCHES ---
S80VOFF = $C00C
DHIROFF = $C05F
S80SOFF = $C000
PAGE2OF = $C054
GRAPH = $C050
LORES = $C056
FULLSC = $C052

* --- ZP POINTER (NON-PRODOS, TRANSIENT) ---
LINEP = $06

* === RENDER STATE (INLINE STORAGE) ===
CHAN DS 1
GENB DS 1
GENA DS 1
LIVEBAS DS 2
PROD DS 1
MTMP DS 1
NTMP DS 1
RTOP DS 1
RBOT DS 1
COLBYTE DS 1
MASK DS 1
OUTB DS 1
YROW DS 1
GRLO DS 24
GRHI DS 24
GBUF DS 240

* === GRON: UNDO DHGR, THEN ENABLE LO-RES ===
GRON
 STA S80VOFF
 STA DHIROFF
 STA S80SOFF
 STA PAGE2OF
 STA GRAPH
 STA LORES
 STA FULLSC
 RTS

* === GRINIT: BUILD 24-ENTRY TEXT-LINE TABLE ===
* TEXTBASE(Y) = $400 + (Y&7)*$80 + (Y>>3)*$28
GRINIT
 LDX #0
GILP
 TXA
 AND #7
 STA NTMP
 LSR
 CLC
 ADC #4
 STA GRHI,X
 LDA NTMP
 AND #1
 BEQ GILO0
 LDA #$80
 JMP GISETL
GILO0
 LDA #0
GISETL
 STA GRLO,X
 TXA
 LSR
 LSR
 LSR
 TAY
 BEQ GIDONE
GIADD
 LDA GRLO,X
 CLC
 ADC #$28
 STA GRLO,X
 DEY
 BNE GIADD
GIDONE
 INX
 CPX #24
 BNE GILP
 RTS

* === GRCLR: ZERO 40 BYTES PER TEXT LINE ===
* USES LINE TABLE (SPARES SCREEN HOLES)
GRCLR
 LDX #0
GCROW
 LDA GRLO,X
 STA LINEP
 LDA GRHI,X
 STA LINEP+1
 LDY #0
 LDA #0
GCCOL
 STA (LINEP),Y
 INY
 CPY #GWIDTH
 BNE GCCOL
 INX
 CPX #24
 BNE GCROW
 RTS

* === RENDER: BLIT UNIVERSE CHAN TO GR ===
RENDER
RETRY
* READ GEN[CHAN] -> GENB
 LDA #MBANK
 STA SDM_BANK
 LDA #0
 STA SDM_BANK+1
 LDA #$20
 CLC
 ADC CHAN
 STA SDM_ADDR
 LDA #0
 STA SDM_ADDR+1
 JSR SDM_READ
 LDA SDM_VAL
 STA GENB
* READ FRONT[CHAN] -> LIVE BASE
 LDA #MBANK
 STA SDM_BANK
 LDA #0
 STA SDM_BANK+1
 LDA #$10
 CLC
 ADC CHAN
 STA SDM_ADDR
 LDA #0
 STA SDM_ADDR+1
 JSR SDM_READ
 LDA SDM_VAL
 BNE RFRONT
 LDA #<BUFA
 STA LIVEBAS
 LDA #>BUFA
 STA LIVEBAS+1
 JMP RBASEOK
RFRONT
 LDA #<BUFB
 STA LIVEBAS
 LDA #>BUFB
 STA LIVEBAS+1
RBASEOK
* GRID BANK = UBASE+CHAN, ADDR = LIVEBASE
 LDA #UBASE
 CLC
 ADC CHAN
 STA SDM_BANK
 LDA #0
 STA SDM_BANK+1
 JSR SDM_SETBANK
 LDA LIVEBAS
 STA SDM_ADDR
 LDA LIVEBAS+1
 STA SDM_ADDR+1
 JSR SDM_SETADDR
* READ 240 CONTIGUOUS GRID BYTES (48*5)
 LDY #0
RDGLP
 JSR SDM_RDNEXT
 LDA SDM_VAL
 STA GBUF,Y
 INY
 CPY #240
 BNE RDGLP
* RE-READ GEN[CHAN] -> GENA
 LDA #MBANK
 STA SDM_BANK
 LDA #0
 STA SDM_BANK+1
 LDA #$20
 CLC
 ADC CHAN
 STA SDM_ADDR
 LDA #0
 STA SDM_ADDR+1
 JSR SDM_READ
 LDA SDM_VAL
 STA GENA
 CMP GENB
 BEQ SNAPOK
 JMP RETRY
SNAPOK
* EXPAND: Y=0..23, X=0..39
 LDA #0
 STA YROW
EXROW
* RTOP = (2*YROW)*5, RBOT = RTOP+5
 LDA YROW
 ASL
 JSR MUL5
 LDA PROD
 STA RTOP
 CLC
 ADC #5
 STA RBOT
* LINEP = TEXTBASE(YROW)
 LDX YROW
 LDA GRLO,X
 STA LINEP
 LDA GRHI,X
 STA LINEP+1
 LDY #0
EXCOL
* COLBYTE = X>>3
 TYA
 LSR
 LSR
 LSR
 STA COLBYTE
* MASK = BIT (X&7)
 TYA
 AND #7
 TAX
 LDA BITMASK,X
 STA MASK
 LDA #0
 STA OUTB
* TOP CELL -> LOW NIBBLE
 LDA RTOP
 CLC
 ADC COLBYTE
 TAX
 LDA GBUF,X
 AND MASK
 BEQ EXTOP0
 LDA #$0F
 STA OUTB
EXTOP0
* BOTTOM CELL -> HIGH NIBBLE
 LDA RBOT
 CLC
 ADC COLBYTE
 TAX
 LDA GBUF,X
 AND MASK
 BEQ EXBOT0
 LDA OUTB
 ORA #$F0
 STA OUTB
EXBOT0
 LDA OUTB
 STA (LINEP),Y
 INY
 CPY #GWIDTH
 BNE EXCOL
 INC YROW
 LDA YROW
 CMP #24
 BNE EXROW
 RTS

* === MUL5: PROD = A * 5 (A*4 + A) ===
MUL5
 STA MTMP
 ASL
 ASL
 CLC
 ADC MTMP
 STA PROD
 RTS

* === MAIN: MINIMAL (TASK 4 REPLACES) ===
MAIN
 JSR SDM_READY
 BCC MRDY
 RTS
MRDY
 JSR GRINIT
 JSR GRON
 JSR GRCLR
 LDA #0
 STA CHAN
 JSR RENDER
 RTS

* BIT0 = LEFTMOST CELL
BITMASK
 DFB $01,$02,$04,$08,$10,$20,$40,$80
