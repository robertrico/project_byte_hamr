********************************
*   READING FROM PERIPHERAL    *
********************************
 ORG $8000
SLOT = 4
SLOTBASE = SLOT*16+$C080
REG_CHAN EQU SLOTBASE+$00
REG_ADDR EQU SLOTBASE+$01
REG_DATA EQU SLOTBASE+$02
REG_CMD EQU SLOTBASE+$03
REG_STAT EQU SLOTBASE+$04
REG_STRCH EQU SLOTBASE+$05
REG_OUT EQU SLOTBASE+$06
 JMP MAIN

MAIN
 LDA #$00
 STA REG_CHAN
 STA REG_ADDR
 STA REG_DATA
 LDA #$FE
 STA REG_CMD
 LDA #$CA
 STA REG_STAT
 LDA #$01
 STA REG_STRCH
 LDA REG_OUT
 LDA #$00
 STA REG_CMD
 STA REG_STAT
 LDA #$02
 STA REG_STRCH
 LDA REG_OUT

 END
